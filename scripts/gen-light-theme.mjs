// Generates src/theme-light.css: the colour-token table of the light theme (v1.2.2, decision D1).
// The UI is written with the dark Tailwind colour classes (bg-slate-950, text-cyan-300, ...). Tailwind v4 compiles every colour utility to var(--color-<hue>-<shade>),
// so re-defining those variables under :root[data-theme="light"] turns the whole site light without touching a class name. Remove the attribute and the site is dark again.
// Usage: node scripts/gen-light-theme.mjs   (reads node_modules/tailwindcss/theme.css; the output is committed, the generator is only needed to change the table)
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const theme = fs.readFileSync(path.join(root, 'node_modules', 'tailwindcss', 'theme.css'), 'utf8');
const palette = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (palette[m[1]] ??= {})[m[2]] = m[3].trim();

// Neutral scale: dark surfaces become light, light text becomes dark. 500 is the dimmest text that still reads on white (4.7:1).
const SLATE = {50: '900', 100: '800', 200: '700', 300: '600', 400: '500', 500: '500', 600: '400', 700: '300', 800: '200', 900: 'white', 950: '50'};
// Coloured scales: tinted dark panels (900/950) become pale tints, light text (100-400) becomes dark text; 500 and 600 (solid buttons, accents) stay.
const COLOUR = {50: '950', 100: '900', 200: '800', 300: '700', 400: '700', 500: '500', 600: '600', 700: '300', 800: '200', 900: '100', 950: '50'};

const lines = [];
for (const [hue, shades] of Object.entries(palette)) {
  if (hue === 'white' || hue === 'black') continue;
  const map = hue === 'slate' ? SLATE : COLOUR;
  for (const shade of Object.keys(shades)) {
    const from = map[shade];
    if (from === undefined) continue;
    const value = from === 'white' ? '#ffffff' : shades[from];
    if (value && value !== shades[shade]) lines.push(`  --color-${hue}-${shade}: ${value};`);
  }
}
const css = `/* GENERATED by scripts/gen-light-theme.mjs (colour-token table of the light theme, v1.2.2). Do not edit by hand; edit the generator.
   Tailwind v4 utilities read var(--color-<hue>-<shade>), so these overrides re-colour every bg-/text-/border-/ring-… class at once.
   Rollback: remove data-theme="light" from <html> (index.html) and the site is dark again. */
:root[data-theme="light"] {
${lines.join('\n')}
}
`;
fs.writeFileSync(path.join(root, 'src', 'theme-light.css'), css);
console.log(`wrote src/theme-light.css (${lines.length} variables, ${Object.keys(palette).length} hues)`);
