import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {BUNDLED_PACKAGES_MANIFEST} from './bundled-packages-plugin.mjs';

/**
 * v1.4.1 stop 21 (B): appends the third-party license list of the npm packages that are REALLY bundled into dist to dist/THIRD_PARTY_NOTICES.txt (the file scripts/prepare-assets.mjs makes from docs/licenses/ and
 * the data-source section). The package list comes from the build itself (scripts/bundled-packages-plugin.mjs records the modules of every output chunk, main page and Web Workers); for each package the name, version,
 * license identifier, copyright lines and the FULL license text come from the package's own files in node_modules. Nothing is written by hand; a package without a license file is listed as such, never filled in.
 * Usage: node scripts/append-npm-notices.mjs [notices file (default dist/THIRD_PARTY_NOTICES.txt)] [manifest (default node_modules/.cache/specreader/bundled-packages.json)]
 */
export const GENERATED_MARK = '=== npm packages bundled into this build (generated by scripts/append-npm-notices.mjs from the build itself) ===';
/** packages whose npm tarball has no license file but whose official notice is kept in the repository (docs/licenses/); used ONLY when the package has none of its own */
const REPOSITORY_NOTICE = {'@rdkit/rdkit': 'docs/licenses/RDKit.txt'};
/** v1.4.1 stop 22: where a license text was looked for and not found (the list says so instead of leaving the gap unexplained). Only used when the package really has no license file. Nothing is made up. */
const SEARCH_NOTES = {
  // none at present (v1.4.2 stop 34: the median-quickselect entry was removed; stop 33 replaced that package by vendor/median-select)
};
const LICENSE_FILE = /^(licen[sc]e|copying|notice|unlicense)([-._].*)?$/i;

const readJson = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const authorText = a => (a == null ? '' : typeof a === 'string' ? a : [a.name, a.email && `<${a.email}>`, a.url].filter(Boolean).join(' '));
const licenseField = j => (typeof j.license === 'string' ? j.license : j.license?.type ?? (Array.isArray(j.licenses) ? j.licenses.map(l => l.type).join(' OR ') : '') ?? '');

/** package root of a manifest entry; virtual entries (vite preload helper, rolldown runtime) are resolved from the installed vite / rolldown packages. */
function packageRoot(entry, projectRoot) {
  if (entry.root) return entry.root;
  const req = createRequire(path.join(projectRoot, 'package.json'));
  if (entry.name === 'vite') return path.dirname(req.resolve('vite/package.json'));
  if (entry.name === 'rolldown') return path.dirname(createRequire(fs.realpathSync(path.join(path.dirname(req.resolve('vite/package.json')), 'package.json'))).resolve('rolldown/package.json'));
  return null;
}

export function collectNotices(manifestPath = BUNDLED_PACKAGES_MANIFEST, projectRoot = process.cwd()) {
  const manifest = readJson(manifestPath);
  const rows = [];
  for (const entry of Object.values(manifest.packages)) {
    const root = packageRoot(entry, projectRoot);
    const row = {name: entry.name, virtual: !entry.root, chunks: entry.chunks, root, version: '', license: '', author: '', repository: '', files: [], copyright: [], missing: []};
    if (!root || !fs.existsSync(path.join(root, 'package.json'))) { row.missing.push('package.json not found'); rows.push(row); continue; }
    const j = readJson(path.join(root, 'package.json'));
    row.version = j.version ?? ''; row.license = licenseField(j); row.author = authorText(j.author); row.repository = typeof j.repository === 'string' ? j.repository : j.repository?.url ?? '';
    for (const f of fs.readdirSync(root).sort()) if (LICENSE_FILE.test(f) && fs.statSync(path.join(root, f)).isFile()) row.files.push({file: f, text: fs.readFileSync(path.join(root, f), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trimEnd()});
    if (!row.files.length && REPOSITORY_NOTICE[entry.name]) {
      const rp = path.join(projectRoot, REPOSITORY_NOTICE[entry.name]);
      if (fs.existsSync(rp)) row.files.push({file: `${REPOSITORY_NOTICE[entry.name]} (kept in the SpecReader repository: the npm package ships no license file)`, text: fs.readFileSync(rp, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n').trimEnd()});
    }
    const seen = new Set();
    for (const {text} of row.files) for (const line of text.split('\n')) if (/^\s*(copyright\s*(\(c\)|©|\d)|\(c\)\s*\d{4}|©)/i.test(line)) { const t = line.trim(); if (!seen.has(t) && seen.size < 6) { seen.add(t); row.copyright.push(t); } }
    if (!row.files.length) { row.missing.push('no license file in the package (LICENSE / LICENCE / COPYING / NOTICE)'); if (SEARCH_NOTES[entry.name]) row.searched = SEARCH_NOTES[entry.name]; }
    if (!row.license) row.missing.push('no license field in package.json');
    rows.push(row);
  }
  return rows.sort((a, b) => a.name.localeCompare(b.name));
}

export function renderNotices(rows) {
  const out = [GENERATED_MARK, '',
    `${rows.length} packages. For each: name, version, license identifier (package.json), copyright lines (copied from the license file), and the full license text (copied from the package).`, ''];
  out.push('Index'); for (const r of rows) out.push(`  - ${r.name}${r.version ? ` ${r.version}` : ''}  [${r.license || 'license not stated'}]${r.virtual ? '  (helper code bundled from the build tool)' : ''}${r.missing.length ? '  ** MISSING: ' + r.missing.join('; ') : ''}`);
  for (const r of rows) {
    out.push('', '-'.repeat(78), `${r.name} ${r.version}`, '-'.repeat(78), `License:    ${r.license || '(not stated in package.json)'}`);
    if (r.repository) out.push(`Repository: ${r.repository}`);
    if (r.author) out.push(`Author (package.json): ${r.author}`);
    if (r.virtual) out.push(`Note:       the preload helper / runtime code that the build tool inserts into the bundle (${r.chunks.join(', ')}).`);
    out.push(`Copyright:  ${r.copyright.length ? '' : '(no copyright line in the license file)'}`); for (const c of r.copyright) out.push(`  ${c}`);
    if (r.missing.length) out.push(`!! MISSING: ${r.missing.join('; ')}`);
    if (r.searched) out.push(`Search for a license text: ${r.searched}`);
    for (const f of r.files) out.push('', `[${f.file}]`, f.text);
  }
  return out.join('\n') + '\n';
}

export function appendNotices(noticesPath, manifestPath = BUNDLED_PACKAGES_MANIFEST, projectRoot = process.cwd()) {
  const rows = collectNotices(manifestPath, projectRoot);
  let base = fs.readFileSync(noticesPath, 'utf8');
  const at = base.indexOf(GENERATED_MARK); if (at >= 0) base = base.slice(0, at).replace(/\s*(-{3,}\s*)?$/, '');   // idempotent: a second run replaces the generated part
  fs.writeFileSync(noticesPath, base.trimEnd() + '\n\n---\n\n' + renderNotices(rows));
  return rows;
}

if (import.meta.url === new URL(process.argv[1], 'file:///').href || process.argv[1]?.endsWith('append-npm-notices.mjs')) {
  const noticesPath = process.argv[2] ?? path.join('dist', 'THIRD_PARTY_NOTICES.txt');
  const rows = appendNotices(noticesPath, process.argv[3] ?? BUNDLED_PACKAGES_MANIFEST);
  const missing = rows.filter(r => r.missing.length);
  console.log(`[notices] ${rows.length} bundled npm packages appended to ${noticesPath}`);
  for (const r of rows) console.log(`  ${r.name}@${r.version} ${r.license}${r.missing.length ? '  MISSING: ' + r.missing.join('; ') : ''}`);
  if (missing.length) console.warn(`[notices] ${missing.length} package(s) without a license file / license field: ${missing.map(r => r.name).join(', ')} (listed in the file as MISSING, nothing was invented)`);
}
